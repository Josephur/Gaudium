#!/usr/bin/env python3
"""Writes `gaudium/src/tokenizer/char_classes.rs`: the character classes of the letter-case
pre-tokenizer pattern (the `Split` regex of the Inkling 2 `tokenizer.json`), as the reference
tokenizer library's own regular-expression engine sees them.

The classes are not read from a Unicode database: the reference engine's Unicode version is
newer than many hosts' tables, and only its behaviour counts. Each code point is put through the
reference pre-tokenizer in five small probe strings, and its class follows from which probes stay
one piece:

  "1" + c     one piece  <=>  c is a number (N)
  "a" + c     one piece  <=>  c is lowercase-like (Ll, Lm, Lo, M)
  "A" + c     one piece  <=>  c is a letter or a mark (L, M)
  "!!" + c    one piece  <=>  c is neither space, letter nor number (marks included), or CR / LF
  c + "Aa"    one piece  <=>  c may start an uppercase run (Lu, Lt, Lm, Lo, M) or prefix one

Usage (in a venv with the `tokenizers` package):
  python3 make_char_classes.py <model dir with tokenizer.json> <output .rs>
"""
import sys
from tokenizers import Tokenizer

# class ids written to the table (keep in step with `CharClass` in the Rust source)
OTHER, UPPER, LOWER, BOTH, MARK, NUMBER, SPACE = range(7)
NAMES = ["Other", "Upper", "Lower", "Both", "Mark", "Number", "Space"]


def main():
    tok = Tokenizer.from_file(sys.argv[1] + "/tokenizer.json")
    pre = tok.pre_tokenizer

    def one(s):
        return len(pre.pre_tokenize_str(s)) == 1

    cls = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            cls.append(OTHER)  # not a char in Rust
            continue
        c = chr(cp)
        if c in "\r\n":
            cls.append(SPACE)
            continue
        if one("1" + c):
            k = NUMBER
        elif one("a" + c):
            if one("!!" + c):
                k = MARK
            elif one(c + "Aa"):
                k = BOTH
            else:
                k = LOWER
        elif one("A" + c):
            k = UPPER
        elif one("!!" + c):
            k = OTHER
        else:
            k = SPACE
        cls.append(k)
    runs = []
    for cp, k in enumerate(cls):
        if not runs or runs[-1][1] != k:
            runs.append((cp, k))
    with open(sys.argv[2], "w") as f:
        f.write("// @generated by gaudium/tests/data/tokenizer/make_char_classes.py: do not edit.\n")
        f.write("// Runs of the letter-case pattern's character classes: `(first code point << 3) | class`,\n")
        f.write("// ascending; a run lasts until the next entry.\n")
        f.write("pub(super) const CLASS_RUNS: [u32; %d] = [\n" % len(runs))
        line = "   "
        for cp, k in runs:
            item = " 0x%x," % ((cp << 3) | k)
            if len(line) + len(item) > 99:
                f.write(line + "\n")
                line = "   "
            line += item
        f.write(line + "\n];\n")
    counts = [0] * 7
    for k in cls:
        counts[k] += 1
    print(len(runs), "runs;", ", ".join(f"{NAMES[i]} {counts[i]}" for i in range(7)))


if __name__ == "__main__":
    main()
